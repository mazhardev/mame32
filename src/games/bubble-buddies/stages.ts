export interface StagePlan {
  index: number;
  boss: number | null;
  layout: string[];
  enemies: EnemyKind[];
  /** Special bubbles that drift up from the floor in this stage. */
  special: 'none' | 'lightning' | 'fire';
}

export function stagePlan(index: number): StagePlan {
  const bossIdx = BOSS_STAGES.indexOf(index);
  if (bossIdx >= 0) return { index, boss: bossIdx, layout: BOSS_LAYOUT, enemies: [], special: 'lightning' };
  const rng = createRng(`bubble-${index}`);
  const layout = LAYOUTS[(index * 3) % LAYOUTS.length];
  const tier = Math.floor(index / 10);
  const count = Math.min(8, 3 + Math.floor((index % 10) / 3) + tier);
  const pool: EnemyKind[] =
    tier === 0 ? (index < 3 ? ['windup'] : ['windup', 'windup', 'hopper'])
    : tier === 1 ? ['windup', 'hopper', 'drifter']
    : ['windup', 'hopper', 'drifter', 'thrower', 'thrower'];
  const enemies: EnemyKind[] = [];
  for (let i = 0; i < count; i++) enemies.push(pool[rng.int(0, pool.length)]);
  if (index === 10) enemies[0] = 'drifter';
  if (index === 20) enemies[0] = 'thrower';
  const special = index > 4 && index % 4 === 1 ? 'lightning' : index > 6 && index % 4 === 3 ? 'fire' : 'none';
  return { index, boss: null, layout, enemies, special };
}
