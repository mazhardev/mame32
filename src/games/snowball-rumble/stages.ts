export const FLOOR_COUNT = FLOORS.length;
export const isBossFloor = (i: number) => i % 10 === 9;
export const zoneOf = (i: number) => Math.floor(i / 10);

const cache = new Map<number, Stage>();
export function floorStage(i: number): Stage {
  let s = cache.get(i);
  if (!s) {
    s = buildStage(FLOORS[i]);
    cache.set(i, s);
  }
  return s;
}

