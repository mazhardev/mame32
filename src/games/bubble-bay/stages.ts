export const LEVEL_COUNT = LEVELS.length;
export const isBossLevel = (i: number) => i % 10 === 9;
export const areaOf = (i: number) => Math.floor(i / 10);
export const AREAS = ['The Shallows', 'Kelp Forest', 'Deep Trench'];

const cache = new Map<number, Stage>();
export function levelStage(i: number): Stage {
  let s = cache.get(i);
  if (!s) {
    s = buildStage(LEVELS[i], { wrap: true });
    cache.set(i, s);
  }
  return s;
}

