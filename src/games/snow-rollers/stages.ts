export const STAGES = 30;
export const PER_LAND = 10;
export const LANDS = ['Frosty Glade', 'Twilight Ridge', 'Ember Glacier'];
export const BOSSES = ['Big Lumpkin', 'Gloomwing', 'Magmaw'];

export interface StagePlan {
  index: number;
  land: number;
  boss: boolean;
  layout: string[];
  enemies: EnemyKind[];
}

/** What a stage contains. Deterministic, so a stage is always the same. */
export function stagePlan(index: number): StagePlan {
  const land = Math.floor(index / PER_LAND);
  const k = index % PER_LAND;
  if (k === PER_LAND - 1) return { index, land, boss: true, layout: BOSS_LAYOUT, enemies: [] };
  const rng = createRng(`snow-${index}`);
  const layout = LAYOUTS[(index * 4 + land) % LAYOUTS.length];
  const count = Math.min(8, 3 + Math.floor(k / 2) + land);
  const pool: EnemyKind[] =
    land === 0 ? (k < 3 ? ['imp'] : ['imp', 'imp', 'hopper']) : land === 1 ? ['imp', 'hopper', 'wisp', 'hopper'] : ['imp', 'hopper', 'flamer', 'wisp', 'flamer'];
  const enemies: EnemyKind[] = [];
  for (let i = 0; i < count; i++) enemies.push(pool[rng.int(0, pool.length)]);
  // Each land's new enemy shows up early so it is introduced gently.
  if (land === 1 && k === 1) enemies[0] = 'wisp';
  if (land === 2 && k === 1) enemies[0] = 'flamer';
  return { index, land, boss: false, layout, enemies };
}
