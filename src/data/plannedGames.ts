import { categoryName } from './categories';
import type { Difficulty, GameCategory, GameDefinition } from '@/types';

type Row = [id: string, title: string, difficulty: Difficulty, icon: string, tags: string];

/**
 * Catalog entries for games that are designed but not yet implemented.
 * They are shown in the catalog clearly marked "Planned" and cannot be launched.
 * When a game is implemented its real definition is added to the games registry,
 * which automatically supersedes the planned entry with the same id.
 */
function planned(category: GameCategory, rows: Row[]): GameDefinition[] {
  return rows.map(([id, title, difficulty, icon, tags]) => ({
    id,
    title,
    shortDescription: `${title} — planned ${categoryName(category).toLowerCase()} game.`,
    fullDescription: `${title} is on the roadmap for the ${categoryName(category)} category. It is listed here so you can see the full planned catalog; it is not playable yet.`,
    category,
    difficulty,
    tags: tags.split(' ').filter(Boolean),
    icon,
    controls: {},
    supportsTouch: true,
    supportsKeyboard: true,
    multiplayer: 'single' as const,
    estimatedMinutes: 5,
    hasHighScore: true,
    hasAchievements: false,
    status: 'planned' as const,
    instructions: {
      howToPlay: ['This game has not been implemented yet.'],
      objective: 'Coming soon.',
    },
  }));
}

