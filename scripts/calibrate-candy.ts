/**
 * Calibrates Candy Match move limits and score targets.
 *
 *   npx vite-node scripts/calibrate-candy.ts
 *
 * For every level a bot (src/games/candy-match/bot.ts) set to play like a
 * casual player — its best move 60% of the time, any legal move otherwise —
 * plays many games. The move limit comes from how many moves it needed, with
 * headroom that shrinks as the saga goes on; if it fails too often even with
 * plenty of moves, the level's layout is eased and tried again. Score levels
 * get a fixed move limit and a target from random play (see SCORE_SHARE). The result is written
 * to src/games/candy-match/calibration.ts.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { botPlay } from '../src/games/candy-match/bot';
import { LEVEL_COUNT, LEVELS_PER_WORLD, designLevel } from '../src/games/candy-match/levels';
import type { Level } from '../src/games/candy-match/levels';

const GAMES = 30;
const CAP = 70;
const SKILL = 0.6;
const MAX_FAILS = 4;
const MAX_EASE = 4;
/** Headroom over the casual player's typical move count, per world. */
const HEADROOM = [1.3, 1.2, 1.15, 1.12, 1.1, 1.08, 1.05, 1.05];
/**
 * Score targets are set against purely random play (which anyone beats) times
 * this factor per world. Cascades make scores swing a lot, so this is kinder
 * than basing them on the stronger player.
 */
const SCORE_SHARE = [0.7, 0.8, 0.9, 1.0, 1.05, 1.1, 1.15, 1.2];

const percentile = (xs: number[], p: number) => {
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.floor(p * s.length))];
};

const out: [number, number, number][] = [];
for (let i = 0; i < LEVEL_COUNT; i++) {
  const world = Math.floor(i / LEVELS_PER_WORLD);
  if (designLevel(i).scoreGoal) {
    const d = designLevel(i);
    const moves = 24 - Math.floor(world / 2);
    const lvl: Level = { index: i, world, moves, layout: d.layout, goals: d.goals };
    const scores = Array.from({ length: GAMES }, (_, g) => botPlay(lvl, `cal-${i}-${g}`, moves, 0).score);
    const target = Math.max(1500, Math.round((percentile(scores, 0.3) * SCORE_SHARE[world]) / 500) * 500);
    out.push([moves, target, 0]);
    console.log(`level ${i + 1}: score ${target} in ${moves} moves`);
    continue;
  }
  // Ease the layout until the bot almost always finishes inside the cap.
  for (let ease = 0; ease <= MAX_EASE; ease++) {
    const d = designLevel(i, ease);
    const lvl: Level = { index: i, world, moves: CAP, layout: d.layout, goals: d.goals };
    const used = Array.from({ length: GAMES }, (_, g) => {
      const r = botPlay(lvl, `cal-${i}-${g}-${ease}`, CAP, SKILL);
      return r.won ? r.movesUsed : CAP + 10;
    });
    const fails = used.filter((u) => u > CAP).length;
    if (fails > MAX_FAILS && ease < MAX_EASE) continue;
    const typical = percentile(used, 0.65);
    const moves = Math.max(12, Math.min(50, Math.ceil(typical * HEADROOM[world])));
    out.push([moves, 0, ease]);
    console.log(`level ${i + 1}: ${d.goals.map((g) => g.kind).join('+')} → ${moves} moves (casual p65 ${typical}, ease ${ease}${fails ? `, ${fails} fails` : ''})`);
    break;
  }
}

const file = path.resolve(__dirname, '../src/games/candy-match/calibration.ts');
writeFileSync(
  file,
  `/**
 * Generated by scripts/calibrate-candy.ts — do not edit by hand.
 * One entry per level: [move limit, score target (score levels only), ease].
 */
export const CALIBRATION: [number, number, number][] = [
${out.map(([m, s, e]) => `  [${m}, ${s}, ${e}],`).join('\n')}
];
`,
);
console.log(`wrote ${file}`);
