/**
 * Proves every Leap Quest level can be finished and stores a winning route
 * for each one in src/games/leap-quest/solutions.ts. The level tests replay
 * these routes with the real movement code, so a level edit that makes a
 * gap too wide or a ledge too high fails the tests.
 *
 *   npx vite-node scripts/solve-leap-quest.ts
 *
 * Re-run it after changing levels.ts or the movement constants in player.ts.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { LEVEL_COUNT, buildLevel } from '../src/games/leap-quest/levels';
import { solveLevel } from '../src/games/leap-quest/solver';

const routes: string[] = [];
let failed = false;
for (let i = 0; i < LEVEL_COUNT; i++) {
  const level = buildLevel(i);
  const t = Date.now();
  const r = solveLevel(level, 600_000);
  console.log(`${level.code} ${level.name}: ${r.ok ? `solved in ${r.inputs.length} steps` : 'NOT SOLVED'} (${r.expanded} states, ${Date.now() - t} ms)`);
  if (!r.ok) failed = true;
  routes.push(r.inputs);
}
if (failed) {
  console.error('Some levels could not be solved; solutions.ts was not written.');
  process.exit(1);
}
const file = path.resolve(__dirname, '../src/games/leap-quest/solutions.ts');
writeFileSync(
  file,
  `/**
 * Generated by scripts/solve-leap-quest.ts — do not edit by hand.
 * One winning route per level: L/N/R = left/none/right, lower case = jump held,
 * each letter lasting 6 frames (1/10 s).
 */
export const SOLUTIONS: string[] = [
${routes.map((r) => `  '${r}',`).join('\n')}
];
`,
);
console.log(`wrote ${file}`);
