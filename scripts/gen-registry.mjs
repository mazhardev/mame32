/**
 * Writes src/games/registry.generated.ts: one static import per game folder
 * that has a definition.ts. Next.js has no import.meta.glob, so this keeps
 * games self-registering — adding a folder is enough; this runs before
 * dev, build, typecheck and test.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const gamesDir = join(root, 'src', 'games');
const out = join(gamesDir, 'registry.generated.ts');

const ids = readdirSync(gamesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith('_') && existsSync(join(gamesDir, d.name, 'definition.ts')))
  .map((d) => d.name)
  .sort();

const source = `// Generated by scripts/gen-registry.mjs — do not edit by hand.
/* eslint-disable */
${ids.map((id, i) => `import * as m${i} from './${id}/definition';`).join('\n')}

export const DEFINITION_MODULES: Record<string, Record<string, unknown>> = {
${ids.map((id, i) => `  '${id}': m${i},`).join('\n')}
};
`;

const previous = existsSync(out) ? readFileSync(out, 'utf8') : '';
if (previous !== source) writeFileSync(out, source);
console.log(`registry: ${ids.length} games`);
