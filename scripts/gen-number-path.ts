/**
 * Builds the fixed Number Path level packs (src/games/number-path/levels.ts).
 * Each level is generated from its own seed and checked to have a single
 * solution, which takes a moment for 7×7 grids, so it is done once here
 * rather than in the browser. Run: npx tsx scripts/gen-number-path.ts
 */
import { writeFileSync } from 'node:fs';
import { createRng } from '../src/utils/random';
import { generate } from '../src/games/number-path/engine';

const PACKS = { easy: [5, 6], normal: [6, 7], hard: [7, 8] } as const;
const COUNT = 30;
let out = `// Generated by scripts/gen-number-path.ts — do not edit by hand.\nimport type { Puzzle } from './engine';\n\n`;
out += `/** [size, clue squares, solution path] per level. */\ntype Packed = [number, number[], number[]];\n\n`;
out += `const PACKED: Record<'easy' | 'normal' | 'hard', Packed[]> = {\n`;
for (const [pack, [n, clues]] of Object.entries(PACKS)) {
  out += `  ${pack}: [\n`;
  for (let i = 0; i < COUNT; i++) {
    const p = generate(n, n, clues, createRng(`number-path-${pack}-${i}`).next);
    out += `    [${n}, [${p.clues.join(',')}], [${p.solution.join(',')}]],\n`;
  }
  out += `  ],\n`;
}
out += `};\n\nexport const LEVELS: Record<'easy' | 'normal' | 'hard', Puzzle[]> = {\n`;
out += `  easy: PACKED.easy.map(([n, clues, solution]) => ({ w: n, h: n, clues, solution })),\n`;
out += `  normal: PACKED.normal.map(([n, clues, solution]) => ({ w: n, h: n, clues, solution })),\n`;
out += `  hard: PACKED.hard.map(([n, clues, solution]) => ({ w: n, h: n, clues, solution })),\n};\n`;
writeFileSync('src/games/number-path/levels.ts', out);
console.log('written');
